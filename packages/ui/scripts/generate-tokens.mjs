// Generates src/tokens.ts from design/tokens.json (+ tokens.extra.json).
//
//   pnpm tokens          rewrite src/tokens.ts
//   pnpm tokens:check    fail if src/tokens.ts is out of date (used by CI)
//
// WHY generate: the design file is the single source of truth. Screens import
// typed constants from tokens.ts, so a colour can only change by changing the
// design file and re-running this script. Nobody hand-types a hex code.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const designPath = resolve(here, '../../../design/tokens.json');
const extraPath = resolve(here, '../tokens.extra.json');
const outPath = resolve(here, '../src/tokens.ts');

const design = JSON.parse(readFileSync(designPath, 'utf8'));
const extra = JSON.parse(readFileSync(extraPath, 'utf8'));

/** Merge one token group, refusing to let the supplement override the design. */
function merge(group) {
  const base = design[group] ?? {};
  const more = extra[group] ?? {};
  for (const key of Object.keys(more)) {
    if (key in base) {
      throw new Error(
        `tokens.extra.json redefines ${group}.${key}, which design/tokens.json already has. Remove it from tokens.extra.json.`,
      );
    }
  }
  return { ...base, ...more };
}

const json = (value) => JSON.stringify(value);

function objectLiteral(entries, indent = '  ') {
  return `{\n${entries.map(([k, v]) => `${indent}${k}: ${v},`).join('\n')}\n}`;
}

const color = merge('color');
const gradients = merge('gradient');
const shadows = merge('shadow');
const radius = merge('radius');

const linear = [];
const radial = [];
for (const [name, g] of Object.entries(gradients)) {
  const colors = json(g.stops.map(([c]) => c));
  const locations = json(g.stops.map(([, at]) => at));
  if (g.type === 'radial') {
    radial.push([
      name,
      `{ center: ${json(g.center)}, colors: ${colors}, locations: ${locations} }`,
    ]);
  } else {
    linear.push([name, `{ angle: ${g.angle}, colors: ${colors}, locations: ${locations} }`]);
  }
}

// React Native's `boxShadow` style takes the same four numbers as CSS box-shadow.
const shadowEntries = Object.entries(shadows).map(([name, s]) => [
  name,
  `[{ offsetX: ${s.x}, offsetY: ${s.y}, blurRadius: ${s.blur}, spreadDistance: 0, color: ${json(s.color)} }]`,
]);

const typeEntries = Object.entries(design.type).map(([name, t]) => {
  const parts = [`size: ${t.size}`];
  if (t.weight !== undefined) parts.push(`weight: ${t.weight}`);
  if (t.letterSpacing !== undefined) parts.push(`letterSpacing: ${t.letterSpacing}`);
  if (t.font !== undefined) parts.push(`font: ${json(t.font)}`);
  if (t.colorToken !== undefined) parts.push(`colorToken: ${json(t.colorToken)}`);
  return [name, `{ ${parts.join(', ')} }`];
});

const plain = (obj) => objectLiteral(Object.entries(obj).map(([k, v]) => [k, json(v)]));

// Motion: only the numbers are generated. The design also writes colours and
// notes here as prose ("#4C1D95 on lavender icons…"); components pick colours
// from `color` instead.
function cubicBezier(css) {
  const match = /^cubic-bezier\(([^)]+)\)$/.exec(css ?? '');
  if (!match) return undefined;
  const points = match[1].split(',').map(Number);
  if (points.length !== 4 || points.some(Number.isNaN)) {
    throw new Error(`Cannot read the easing "${css}" in design/tokens.json motion.`);
  }
  return points;
}

const motionEntries = Object.entries(design.motion ?? {})
  .filter(([, m]) => typeof m === 'object' && m.duration_ms !== undefined)
  .map(([name, m]) => {
    const parts = [`durationMs: ${m.duration_ms}`, `staggerMs: ${m.stagger_ms}`];
    const easing = cubicBezier(m.easing);
    if (easing) parts.push(`easing: ${json(easing)}`);
    parts.push(`scale: ${json(m.scale)}`, `opacity: ${json(m.opacity)}`);
    return [name, `{ ${parts.join(', ')} }`];
  });

const output = `// AUTO-GENERATED by packages/ui/scripts/generate-tokens.mjs. DO NOT EDIT.
// Sources: design/tokens.json and packages/ui/tokens.extra.json.
// To change a value, change the source file and run \`pnpm tokens\`.

/** Colours. */
export const color = ${plain(color)} as const;

/** Linear gradients. \`angle\` is a CSS angle in degrees; see theme/gradient.ts. */
export const gradient = ${objectLiteral(linear)} as const;

/** Radial gradients (alert screens). */
export const radialGradient = ${objectLiteral(radial)} as const;

/** Shadows, ready for React Native's \`boxShadow\` style. */
export const shadow = ${objectLiteral(shadowEntries)} as const;

/** Corner radii. */
export const radius = ${plain(radius)} as const;

/** Spacing steps. */
export const spacing = ${plain(design.spacing)} as const;

/** Fixed sizes. */
export const size = ${plain(design.size)} as const;

/** Font family names (must match packages/ui/fonts.config.js). */
export const font = ${plain(design.font)} as const;

/** Named text styles. */
export const type = ${objectLiteral(typeEntries)} as const;

/** Repeating waves and ripples. \`easing\` is a CSS cubic-bezier; \`scale\` and \`opacity\` are [from, to]. */
export const motion = ${objectLiteral(motionEntries)} as const;

export type ColorName = keyof typeof color;
export type GradientName = keyof typeof gradient;
export type ShadowName = keyof typeof shadow;
export type RadiusName = keyof typeof radius;
export type TypeName = keyof typeof type;
export type MotionName = keyof typeof motion;
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    // Missing file is reported as out of date below.
  }
  // Compare ignoring line endings so Windows checkouts do not fail the check.
  if (current.replace(/\r\n/g, '\n') !== output) {
    console.error('src/tokens.ts is out of date. Run `pnpm tokens` and commit the result.');
    process.exit(1);
  }
  console.log('src/tokens.ts is up to date.');
} else {
  writeFileSync(outPath, output);
  console.log(
    `Wrote src/tokens.ts: ${Object.keys(color).length} colours, ${linear.length + radial.length} gradients, ${shadowEntries.length} shadows, ${Object.keys(radius).length} radii.`,
  );
}
